test('actual direct swap capture accepts only its exact pre-field review introduction', () => {
  const result = check(capturedSwapScreens, 'swap', publicEmulatorAddress);
  assert.equal(result.passed, true, JSON.stringify(result.failures));
  assert.equal(result.matchedFieldCount, 13);
  const intro = capturedSwapScreens[1];
  assert.equal(check(capturedSwapScreens.map(s => s === intro ? 'Review transaction to | Transfer all tokens' : s), 'swap', publicEmulatorAddress).passed, false);
  assert.equal(check([...capturedSwapScreens.slice(0, 2), intro, ...capturedSwapScreens.slice(2)], 'swap', publicEmulatorAddress).passed, false);
  const late = capturedSwapScreens.filter(s => s !== intro);
  late.splice(4, 0, intro);
  assert.equal(check(late, 'swap', publicEmulatorAddress).passed, false);
  assert.equal(check([intro, ...approvalScreens]).passed, false);
});
